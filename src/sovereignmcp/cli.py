"""sovereignmcp command line.

    sovereignmcp init            create a starter policy.yaml with a real, random admin token
    sovereignmcp serve           run the gateway (refuses demo tokens unless --demo)
    sovereignmcp hash-token      print the SHA-256 for a token (for policy.yaml)
    sovereignmcp verify-audit    check the audit log's hash chain
"""
import argparse
import getpass
import hashlib
import json
import os
import secrets
import sys

import yaml

# SHA-256 of the demo tokens that ship in examples/policy.example.yaml. Never valid in production.
DEMO_HASHES = {
    hashlib.sha256(t.encode()).hexdigest()
    for t in ("demo-intern-token", "demo-manager-token", "demo-cto-token")
}

POLICY_TEMPLATE = """\
# Generated by `sovereignmcp init`.
shadow_mode: true             # observe only: logs what WOULD be blocked. Set to false to enforce.
upstream_url: "http://127.0.0.1:8001/mcp"   # your internal MCP server (env SOVEREIGN_UPSTREAM overrides)
approval_ttl_minutes: 15
sql_dialect: null             # e.g. postgres, mysql, sqlite
default_agent: default_agent
audit_roles: [admin]

# Add one entry per person. `manager:` is who approves their risky calls (needs a user with that id).
users:
  - id: user_admin
    name: Admin
    role: admin
    token_sha256: "{token_hash}"
    allowed_tools: ["*"]

agents:
  default_agent:
    allowed_tools: ["*"]

tool_rules:
  run_sql:
    sql_inspect: true
    sql_arg: query
  run_command:
    command_inspect: true
    command_arg: command
  fetch_url:
    url_inspect: true
    url_arg: url
"""


def sha256_hex(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def check_policy_safety(policy: dict, env=None, allow_demo: bool = False):
    """Returns (problems, warnings). Problems are fatal unless demo mode is explicitly allowed."""
    env = os.environ if env is None else env
    problems, warnings = [], []
    if not allow_demo:
        if any(str(u.get("token_sha256", "")).lower() in DEMO_HASHES for u in policy.get("users", [])):
            problems.append("policy.yaml contains the public DEMO tokens. Run `sovereignmcp init` for real ones.")
        if not env.get("SOVEREIGN_AUDIT_KEY"):
            problems.append("SOVEREIGN_AUDIT_KEY is not set (it protects the audit log from re-forging).")
    elif not env.get("SOVEREIGN_AUDIT_KEY"):
        warnings.append("SOVEREIGN_AUDIT_KEY is not set.")
    if env.get("SOVEREIGN_AUDIT_KEY") and len(env["SOVEREIGN_AUDIT_KEY"]) < 32 and not allow_demo:
        warnings.append("SOVEREIGN_AUDIT_KEY is short; use 32+ random characters.")
    if policy.get("shadow_mode"):
        warnings.append("shadow_mode is ON: nothing is blocked, violations are only logged.")
    return problems, warnings


def cmd_hash_token(args) -> int:
    token = args.token or getpass.getpass("Token (input hidden): ")
    print(sha256_hex(token))
    return 0


def cmd_init(args) -> int:
    if os.path.exists(args.policy) and not args.force:
        print(f"{args.policy} already exists (use --force to overwrite).", file=sys.stderr)
        return 1
    token = secrets.token_urlsafe(32)
    with open(args.policy, "w", encoding="utf-8") as f:
        f.write(POLICY_TEMPLATE.format(token_hash=sha256_hex(token)))
    print(f"Wrote {args.policy} (shadow mode ON).\n")
    print("Admin token (shown ONCE, store it in a secret manager; only its hash is saved):")
    print(f"  {token}\n")
    print("Set an audit-log key before serving:")
    print(f"  export SOVEREIGN_AUDIT_KEY={secrets.token_hex(32)}\n")
    print("Then:  sovereignmcp serve --policy " + args.policy)
    return 0


def cmd_serve(args) -> int:
    policy_path = args.policy
    try:
        with open(policy_path, "r", encoding="utf-8") as f:
            policy = yaml.safe_load(f) or {}
    except OSError as exc:
        print(f"Cannot read {policy_path}: {exc.strerror}. Run `sovereignmcp init` first.", file=sys.stderr)
        return 1
    allow_demo = args.demo or os.environ.get("SOVEREIGN_ALLOW_DEMO_TOKENS") == "1"
    problems, warnings = check_policy_safety(policy, allow_demo=allow_demo)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    if problems:
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        print("Refusing to start. (--demo skips these checks for local demos only.)", file=sys.stderr)
        return 2
    os.environ["SOVEREIGN_POLICY"] = policy_path
    import uvicorn

    uvicorn.run("sovereignmcp.gateway:app", host=args.host, port=args.port)
    return 0


def cmd_verify_audit(args) -> int:
    from sovereignmcp.core.audit import AuditVault

    result = AuditVault(args.db).verify_chain()
    print(json.dumps(result, indent=2))
    return 0 if result.get("valid") else 1


def build_parser() -> argparse.ArgumentParser:
    default_policy = os.environ.get("SOVEREIGN_POLICY", "policy.yaml")
    parser = argparse.ArgumentParser(prog="sovereignmcp", description="Zero-trust gateway for AI agent tool calls.")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init", help="create a starter policy.yaml")
    p.add_argument("--policy", default=default_policy)
    p.add_argument("--force", action="store_true")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("serve", help="run the gateway")
    p.add_argument("--policy", default=default_policy)
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8000)
    p.add_argument("--demo", action="store_true", help="allow the public demo tokens (local demos only)")
    p.set_defaults(func=cmd_serve)

    p = sub.add_parser("hash-token", help="print the SHA-256 of a token")
    p.add_argument("token", nargs="?")
    p.set_defaults(func=cmd_hash_token)

    p = sub.add_parser("verify-audit", help="verify the audit log hash chain")
    p.add_argument("--db", default=os.environ.get("SOVEREIGN_DB", "sovereign_audit.db"))
    p.set_defaults(func=cmd_verify_audit)
    return parser


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
